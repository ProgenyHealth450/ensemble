'use strict';

const fs = require('fs');
const path = require('path');

const ALLOWED_DOC_PATHS = [
  'README.md',
  'AGENTS.md',
  'docs/UserGuide.md',
];

const USER_GUIDE_TEMPLATE = `# User Guide

## Table of Contents

(TOC auto-generated by documentation-specialist on first commit)

## Overview

(Brief project overview — derive from README.md's project description section.)

## Getting Started

(Paste relevant content from README.md's Getting Started section.)

## Commands

(Paste relevant content from README.md's Commands section, expanded with examples.)

## Workflows

(Paste relevant content from README.md's Workflows section, expanded with step-by-step examples.)
`;

function summarizeChangeScope(beadHistory = []) {
  const text = Array.isArray(beadHistory)
    ? beadHistory.map((entry) => (typeof entry === 'string' ? entry : JSON.stringify(entry))).join('\n')
    : String(beadHistory || '');

  const categories = new Set();
  if (/command/i.test(text)) categories.add('added-command');
  if (/agent/i.test(text)) categories.add('added-agent');
  if (/skill/i.test(text)) categories.add('added-skill');
  if (/flag/i.test(text)) categories.add('added-flag');
  if (/env/i.test(text)) categories.add('added-env-var');
  if (/behavior|changed/i.test(text)) categories.add('changed-behavior');
  if (/prd/i.test(text)) categories.add('new-prd-feature');
  if (/trd/i.test(text)) categories.add('new-trd-task');
  if (/removed/i.test(text)) categories.add('removed-feature');
  if (/breaking/i.test(text)) categories.add('breaking-change');
  return [...categories];
}

function shouldBootstrapUserGuide(categories) {
  return categories.some((category) => [
    'added-command',
    'added-flag',
    'added-skill',
    'new-prd-feature',
    'changed-behavior',
  ].includes(category));
}

function normalizeAllowedPath(filePath) {
  return filePath.replace(/^\.\//, '').replace(/^\//, '');
}

function applyScopeGuard(edits = []) {
  const accepted = [];
  const rejectedPaths = [];

  for (const edit of edits) {
    const normalizedPath = normalizeAllowedPath(edit.path || '');
    if (!ALLOWED_DOC_PATHS.includes(normalizedPath)) {
      rejectedPaths.push(normalizedPath);
      continue;
    }
    accepted.push({ ...edit, path: normalizedPath });
  }

  return { accepted, rejectedPaths };
}

function ensureFile(repoRoot, relativePath, content) {
  const absolutePath = path.join(repoRoot, relativePath);
  fs.mkdirSync(path.dirname(absolutePath), { recursive: true });
  fs.writeFileSync(absolutePath, content, 'utf8');
}

function runDocMaintenance(trdMetadata, beadHistory, repoRoot, options = {}) {
  const logs = [];
  const filesUpdated = [];
  const createdFiles = [];

  if (process.env.ENSEMBLE_SKIP_DOC_HOOK === '1') {
    logs.push('INFO: ENSEMBLE_SKIP_DOC_HOOK=1; skipping doc maintenance.');
    return { filesUpdated, createdFiles, logs, skipped: true, reason: 'skip-env' };
  }

  if (options.documentationAgentMissing) {
    logs.push('INFO: documentation-specialist not in agent registry; skipping PR-boundary doc maintenance.');
    return { filesUpdated, createdFiles, logs, skipped: true, reason: 'missing-agent' };
  }

  const categories = options.changeScopeCategories || summarizeChangeScope(beadHistory);
  const userGuidePath = path.join(repoRoot, 'docs/UserGuide.md');
  const userGuideExists = fs.existsSync(userGuidePath);

  if (!userGuideExists && shouldBootstrapUserGuide(categories)) {
    try {
      ensureFile(repoRoot, 'docs/UserGuide.md', USER_GUIDE_TEMPLATE);
      createdFiles.push('docs/UserGuide.md');
      filesUpdated.push('docs/UserGuide.md');
    } catch (error) {
      logs.push(`WARN: documentation-specialist could not update docs/UserGuide.md: ${error.message}. PR will proceed; resolve and commit doc update separately.`);
    }
  }

  const proposedEdits = options.proposedEdits || [];
  const { accepted, rejectedPaths } = applyScopeGuard(proposedEdits);

  for (const edit of accepted) {
    try {
      ensureFile(repoRoot, edit.path, edit.content || '');
      if (!filesUpdated.includes(edit.path)) {
        filesUpdated.push(edit.path);
      }
    } catch (error) {
      logs.push(`WARN: documentation-specialist could not update ${edit.path}: ${error.message}. PR will proceed; resolve and commit doc update separately.`);
    }
  }

  if (rejectedPaths.length > 0) {
    logs.push(`INFO: scope-guard-rejected-paths:${rejectedPaths.join(',')}`);
  }

  if (filesUpdated.length === 0 && createdFiles.length === 0 && !shouldBootstrapUserGuide(categories)) {
    logs.push('INFO: no-user-visible-changes');
  }

  return {
    filesUpdated,
    createdFiles,
    logs,
    categories,
    rejectedPaths,
  };
}

module.exports = {
  ALLOWED_DOC_PATHS,
  USER_GUIDE_TEMPLATE,
  summarizeChangeScope,
  shouldBootstrapUserGuide,
  applyScopeGuard,
  runDocMaintenance,
};
